# ---------------------------------------------------------------------------
# Custom Flowable: coloured badge
# ---------------------------------------------------------------------------
class Badge(Flowable):
    def __init__(self, text, bg_hex, fg_hex, width=70, height=14):
        Flowable.__init__(self)
        self.text   = text
        self.bg     = colors.HexColor(bg_hex)
        self.fg     = colors.HexColor(fg_hex)
        self.width  = width
        self.height = height

    def draw(self):
        self.canv.setFillColor(self.bg)
        self.canv.roundRect(0, 0, self.width, self.height, 3, fill=1, stroke=0)
        self.canv.setFillColor(self.fg)
        self.canv.setFont('Helvetica-Bold', 7)
        self.canv.drawCentredString(self.width / 2, 3, self.text)


# ---------------------------------------------------------------------------
# Page template: header & footer on every page
# ---------------------------------------------------------------------------
def _header_footer(canvas, doc):
    canvas.saveState()
    w, h = A4

    # Top bar
    canvas.setFillColor(BRAND_DARK)
    canvas.rect(0, h - 28, w, 28, fill=1, stroke=0)
    canvas.setFillColor(WHITE)
    canvas.setFont('Helvetica-Bold', 9)
    canvas.drawString(18, h - 18, 'MITRE ATT&CK INCIDENT REPORT')
    canvas.setFont('Helvetica', 8)
    canvas.drawRightString(w - 18, h - 18, f'CONFIDENTIAL  |  Page {doc.page}')

    # Bottom bar
    canvas.setFillColor(GREY_200)
    canvas.rect(0, 0, w, 20, fill=1, stroke=0)
    canvas.setFillColor(GREY_500)
    canvas.setFont('Helvetica', 7)
    canvas.drawString(18, 6, 'Generated by MITRE Incident Mapper  •  Powered by MITRE ATT&CK® Framework')
    canvas.drawRightString(w - 18, 6, datetime.now().strftime('%Y-%m-%d %H:%M UTC'))

    canvas.restoreState()


