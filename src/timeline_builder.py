    def generate_pdf(self, incident: Dict[str, Any]) -> bytes:
        pdf_buffer = BytesIO()
        doc = SimpleDocTemplate(
            pdf_buffer,
            pagesize=A4,
            leftMargin=0.75 * inch,
            rightMargin=0.75 * inch,
            topMargin=0.55 * inch,
            bottomMargin=0.45 * inch,
        )
        styles = self._make_styles()
        story  = []

        events     = incident.get('events', [])
        techniques = incident.get('mitre_techniques', [])

        self._cover_page(story, incident, styles)
        self._tactic_summary(story, events, techniques, styles)
        self._kill_chain(story, events, techniques, styles)
        self._event_timeline(story, events, styles)
        self._recommendations(story, events, styles)

        doc.build(story, onFirstPage=_header_footer, onLaterPages=_header_footer)
        pdf_buffer.seek(0)
        return pdf_buffer.getvalue()
