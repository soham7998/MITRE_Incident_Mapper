# TimelineBuilder
# ---------------------------------------------------------------------------
class TimelineBuilder:
    def build_timeline(self, events: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        sorted_events = sorted(events, key=lambda x: x.get('timestamp', ''))
        timeline_phases: Dict[str, list] = {}
        for event in sorted_events:
            tactic = event.get('mitre_tactic', 'Unknown')
            timeline_phases.setdefault(tactic, []).append(event)
        return [
            {'tactic': t, 'events': timeline_phases[t]}
            for t in TACTICS_ORDER if t in timeline_phases
        ]


