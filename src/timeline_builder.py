    def _rule(self, color=GREY_200, thickness=0.5):
        return HRFlowable(width='100%', thickness=thickness, color=color, spaceAfter=6, spaceBefore=4)

    def _stat_box(self, label, value, bg, fg):
        """Single stat card as a 1-cell table."""
        bg_c = colors.HexColor(bg)
        fg_c = colors.HexColor(fg)
        tbl = Table([[
            Paragraph(f'<font color="{fg}" size="18"><b>{value}</b></font>', ParagraphStyle(
                '_sv', fontSize=18, fontName='Helvetica-Bold',
                textColor=fg_c, alignment=TA_CENTER)),
        ], [
            Paragraph(f'<font color="#64748B" size="7">{label}</font>', ParagraphStyle(
                '_sl', fontSize=7, fontName='Helvetica',
                textColor=GREY_500, alignment=TA_CENTER)),
        ]], colWidths=[1.4 * inch])
        tbl.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), bg_c),
            ('ROUNDEDCORNERS', [4, 4, 4, 4]),
            ('TOPPADDING',    (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('LEFTPADDING',   (0, 0), (-1, -1), 6),
            ('RIGHTPADDING',  (0, 0), (-1, -1), 6),
            ('ALIGN',         (0, 0), (-1, -1), 'CENTER'),
            ('BOX',           (0, 0), (-1, -1), 0.5, colors.HexColor(fg)),
        ]))
        return tbl

